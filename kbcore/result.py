"""五種結果與六個退出碼。這兩組是整個底盤的共用詞彙，其餘模組一律引用這裡。"""
from enum import Enum


class Level(str, Enum):
    """檢查的五種結果。

    PASS / WARN / FAIL 是常見的三級。另外兩種各解一個舊系統的病：

    SKIPPED — 檢查跑不了（缺欄位、前置不成立）。**不是 PASS。**
              「否定訊號要具名」：沒查到、解析失敗、不適用，不可以退化成同一個
              falsy 值，更不可以退化成通過。它的數量本身就是訊號。

    ENV     — 環境狀態（上游還沒更新、端點暫時不通），不是資料故障。
              不計數、不影響退出碼。分出去之後 WARN 才重新有意義——
              「會固定響的警報就是雜訊，而雜訊訓練人忽略警報」。
    """

    PASS = "PASS"
    WARN = "WARN"
    FAIL = "FAIL"
    SKIPPED = "SKIPPED"
    ENV = "ENV"


class Exit:
    """統一退出碼。

    **為什麼從 10 起跳，而不是 1、2、3——這一段不要「整理」掉。**

    2026-08-19 的 tracer bullet 撞到：Python 直譯器開不了腳本檔時回 `exit 2`。
    若我們的 2 表示「不可改寫守衛拒絕」，那麼一個 launchd 條目只要路徑寫錯，
    哨兵就會判讀成「單期檔已存在且內容不同」，然後叫人去掛 errata ——
    **一個完全錯誤、但很有說服力的診斷。**

    這比沉默更危險。低位數字全都被佔用：
      1        通用錯誤
      2        直譯器／shell 誤用
      126      不可執行
      127      找不到指令
      128+n    被 signal 中止

    10–15 沒有任何標準含義。0 維持不變，那是宇宙通則。

    CONFLICT（15）是 2026-08-19 第 4 片加的第七個碼。兩個寫入者共用 main：
    Actions 寫 raw/、Mac 寫 data/，理論上不衝突。**真的衝突代表有東西寫錯了
    地方**——盲目重試或 force push 會得到「看起來成功、但資料被吃掉」，
    那是這整套架構最想避免的失效形態。所以它需要一個自己的碼，不能併進
    CONTENT（改草稿重跑）或 ENVIRONMENT（重跑可能會好）。
    """

    OK = 0            # 成功
    CONTENT = 10      # 內容不合格（有 FAIL，或 SKIPPED 超過閾值）→ 改草稿重跑
    IMMUTABLE = 11    # 不可改寫守衛拒絕 → 改草稿沒有用，掛 errata
    BAD_INPUT = 12    # 輸入壞掉（JSON 解析失敗、缺必要頂層欄位）
    EMPTY_ROUND = 13  # 空輪次 —— **不是失敗，是設計**
    ENVIRONMENT = 14  # 環境／網路失敗 → 重跑可能會好
    CONFLICT = 15     # rebase 衝突 —— 兩個寫入者動到同一個檔案，**重跑不會好**
